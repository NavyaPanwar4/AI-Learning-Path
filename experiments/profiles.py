"""Seeded synthetic learner profiles (mastery vectors over every catalog skill).

Model (documented in the paper's setup section):
  * each skill has a prerequisite depth d(s) (longest chain from a root);
  * a learner has an ability a per TRACK (programming/data/math/ml);
  * mastery(s) = sigmoid(SLOPE * (a_track - d(s) + OFFSET)) + noise, clipped to [0,1].
This makes profiles approximately prerequisite-consistent (deeper skills have
lower mastery) while the noise creates realistic local inconsistencies.
Archetypes differ in how the per-track abilities are drawn.  'edge' profiles
are hand-specified inconsistent cases.  Generation is fully seeded.
"""
from __future__ import annotations

import json
import math
import random
from typing import Dict, List

from app.services.path_planner import SkillGraph

SLOPE = 1.6
OFFSET = 0.5
NOISE_SD = 0.06
TRACKS = ("programming", "data", "math", "ml")

# archetype -> (low, high) ability range of the shared level
ABILITY = {
    "beginner": (-2.0, -0.5),
    "intermediate": (2.0, 3.5),
    "advanced": (6.5, 8.0),
}


def depths(graph: SkillGraph) -> Dict[str, int]:
    d: Dict[str, int] = {}
    for sid in graph.topological_order():
        preds = graph.direct_prereqs(sid)
        d[sid] = 1 + max((d[p] for p in preds), default=-1)
    return d


def _sigmoid(x: float) -> float:
    return 1.0 / (1.0 + math.exp(-x))


def _mastery_vector(graph, tracks, abilities, rng) -> Dict[str, float]:
    d = depths(graph)
    out = {}
    for sid in graph.nodes:
        a = abilities[tracks[sid]]
        m = _sigmoid(SLOPE * (a - d[sid] + OFFSET)) + rng.gauss(0.0, NOISE_SD)
        out[sid] = round(min(1.0, max(0.0, m)), 3)
    return out


def generate_profiles(graph: SkillGraph, tracks: Dict[str, str], seed: int = 20261018,
                      per_archetype: int = 6, dev_per_archetype: int = 2) -> List[dict]:
    rng = random.Random(seed)
    profiles: List[dict] = []
    for arch in ("beginner", "intermediate", "uneven", "advanced"):
        for i in range(per_archetype):
            if arch == "uneven":
                # strong in 1-2 tracks, weak in the others
                strong = set(rng.sample(TRACKS, rng.choice((1, 2))))
                ab = {t: (rng.uniform(5.0, 7.5) if t in strong else rng.uniform(-1.5, 0.5)) for t in TRACKS}
            else:
                lo, hi = ABILITY[arch]
                base = rng.uniform(lo, hi)
                ab = {t: base + rng.uniform(-0.4, 0.4) for t in TRACKS}
            profiles.append({
                "id": f"{arch[:3]}{i + 1:02d}", "archetype": arch,
                "split": "dev" if i < dev_per_archetype else "test",
                "mastery": _mastery_vector(graph, tracks, ab, rng),
                "abilities": {t: round(v, 2) for t, v in ab.items()},
            })
    profiles += edge_profiles(graph, tracks, rng)
    return profiles


def edge_profiles(graph, tracks, rng) -> List[dict]:
    """Hand-specified, deliberately prerequisite-inconsistent learners."""
    def base(level):
        return _mastery_vector(graph, tracks, {t: level for t in TRACKS}, rng)

    # 1. practitioner gap: strong ML/programming, weak linear algebra/calculus/statistics
    m = base(6.5)
    for sid in ("126", "127", "129", "30", "29"):
        m[sid] = round(rng.uniform(0.05, 0.25), 3)
    p1 = {"id": "edg01", "archetype": "edge", "split": "dev", "mastery": m,
          "note": "strong applied ML, weak maths prerequisites"}
    # 2. mathematician: strong maths/statistics, no programming
    m = base(-1.0)
    for sid, n in graph.nodes.items():
        if tracks[sid] == "math":
            m[sid] = round(rng.uniform(0.85, 0.97), 3)
    p2 = {"id": "edg02", "archetype": "edge", "split": "test", "mastery": m,
          "note": "strong maths, beginner programming"}
    # 3. almost ready: advanced except one weak foundational prerequisite
    m = base(9.0)
    m["46"] = round(rng.uniform(0.2, 0.35), 3)  # Machine Learning Fundamentals
    p3 = {"id": "edg03", "archetype": "edge", "split": "test", "mastery": m,
          "note": "advanced learner with one weak intermediate prerequisite"}
    return [p1, p2, p3]


def save_profiles(profiles: List[dict], path: str) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        json.dump({"_status": "Synthetic profiles generated by experiments/profiles.py; seeded.",
                   "profiles": profiles}, fh, indent=1)


def load_profiles(path: str) -> List[dict]:
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)["profiles"]


# ---------------------------------------------------------------------------
# Replication set: more profiles, two learner-generation models
# ---------------------------------------------------------------------------

def _mastery_vector_gaps(graph, tracks, abilities, rng, slope=1.0, noise_sd=0.15,
                         gap_rate=0.12, boost_rate=0.08) -> Dict[str, float]:
    """Alternative learner model: flatter ability curve, larger noise, and random isolated knowledge
    gaps (skill far below expectation) and lucky strengths (far above)."""
    d = depths(graph)
    out = {}
    for sid in graph.nodes:
        m = _sigmoid(slope * (abilities[tracks[sid]] - d[sid] + OFFSET)) + rng.gauss(0.0, noise_sd)
        r = rng.random()
        if r < gap_rate:
            m = rng.uniform(0.05, 0.30)
        elif r < gap_rate + boost_rate:
            m = rng.uniform(0.80, 0.95)
        out[sid] = round(min(1.0, max(0.0, m)), 3)
    return out


def generate_replication_profiles(graph: SkillGraph, tracks: Dict[str, str], seed: int = 20261029,
                                  per_archetype: int = 12, edge_sets: int = 3) -> List[dict]:
    """All profiles get split='rep'. Within each archetype, the first half use the main learner model
    ('depth-sigmoid') and the second half the alternative one ('gap-noise')."""
    rng = random.Random(seed)
    profiles: List[dict] = []
    for arch in ("beginner", "intermediate", "uneven", "advanced"):
        for i in range(per_archetype):
            if arch == "uneven":
                strong = set(rng.sample(TRACKS, rng.choice((1, 2))))
                ab = {t: (rng.uniform(5.0, 7.5) if t in strong else rng.uniform(-1.5, 0.5)) for t in TRACKS}
            else:
                lo, hi = ABILITY[arch]
                base = rng.uniform(lo, hi)
                ab = {t: base + rng.uniform(-0.4, 0.4) for t in TRACKS}
            alt = i >= per_archetype // 2
            mastery = (_mastery_vector_gaps(graph, tracks, ab, rng) if alt
                       else _mastery_vector(graph, tracks, ab, rng))
            profiles.append({"id": f"r{arch[:3]}{i + 1:02d}", "archetype": arch, "split": "rep",
                             "learner_model": "gap-noise" if alt else "depth-sigmoid",
                             "mastery": mastery, "abilities": {t: round(v, 2) for t, v in ab.items()}})
    n = 0
    for _ in range(edge_sets):
        for p in edge_profiles(graph, tracks, rng):
            n += 1
            p = dict(p, id=f"redg{n:02d}", split="rep", learner_model="depth-sigmoid")
            profiles.append(p)
    return profiles
